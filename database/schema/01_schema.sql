CREATE DATABASE IF NOT EXISTS campusconnect CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE campusconnect;
CREATE TABLE IF NOT EXISTS students (
 student_id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE, phone VARCHAR(20), department VARCHAR(100) NOT NULL,
 year_of_study TINYINT UNSIGNED NOT NULL, enrollment_date DATE NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CHECK (year_of_study BETWEEN 1 AND 6)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS clubs (
 club_id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, club_name VARCHAR(120) NOT NULL UNIQUE,
 description TEXT, category ENUM('TECHNICAL','CULTURAL','SPORTS','LITERARY','SOCIAL','OTHER') NOT NULL DEFAULT 'OTHER',
 date_founded DATE, status ENUM('ACTIVE','INACTIVE') NOT NULL DEFAULT 'ACTIVE', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS club_memberships (
 membership_id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 student_id INT UNSIGNED NOT NULL, club_id INT UNSIGNED NOT NULL,
 membership_role ENUM('MEMBER','PRESIDENT','VICE_PRESIDENT','SECRETARY','TREASURER') NOT NULL DEFAULT 'MEMBER',
 membership_status ENUM('ACTIVE','INACTIVE','LEFT') NOT NULL DEFAULT 'ACTIVE', joined_at DATE NOT NULL DEFAULT (CURRENT_DATE),
 UNIQUE KEY uq_membership (student_id,club_id), KEY idx_membership_club(club_id,membership_status),
 CONSTRAINT fk_cm_student FOREIGN KEY(student_id) REFERENCES students(student_id) ON DELETE CASCADE,
 CONSTRAINT fk_cm_club FOREIGN KEY(club_id) REFERENCES clubs(club_id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS venues (
 venue_id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, venue_name VARCHAR(120) NOT NULL UNIQUE,
 building VARCHAR(120) NOT NULL, room_number VARCHAR(30), capacity INT UNSIGNED NOT NULL,
 venue_type ENUM('AUDITORIUM','CLASSROOM','LAB','GROUND','SEMINAR_HALL','OTHER') NOT NULL DEFAULT 'OTHER',
 CHECK(capacity > 0)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS events (
 event_id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, club_id INT UNSIGNED NOT NULL, venue_id INT UNSIGNED NOT NULL,
 event_name VARCHAR(160) NOT NULL, description TEXT, event_date DATE NOT NULL, start_time TIME NOT NULL, end_time TIME NOT NULL,
 capacity INT UNSIGNED NOT NULL, registration_deadline DATETIME NOT NULL,
 event_status ENUM('UPCOMING','ONGOING','COMPLETED','CANCELLED') NOT NULL DEFAULT 'UPCOMING', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 KEY idx_event_date(event_date,event_status),
 CONSTRAINT fk_event_club FOREIGN KEY(club_id) REFERENCES clubs(club_id) ON DELETE RESTRICT,
 CONSTRAINT fk_event_venue FOREIGN KEY(venue_id) REFERENCES venues(venue_id) ON DELETE RESTRICT,
 CHECK(capacity > 0), CHECK(end_time > start_time)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS event_registrations (
 registration_id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, student_id INT UNSIGNED NOT NULL, event_id INT UNSIGNED NOT NULL,
 registered_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 registration_status ENUM('REGISTERED','WAITLISTED','CANCELLED') NOT NULL DEFAULT 'REGISTERED',
 attendance_status ENUM('PENDING','PRESENT','ABSENT') NOT NULL DEFAULT 'PENDING',
 UNIQUE KEY uq_registration(student_id,event_id), KEY idx_reg_event(event_id,registration_status,registered_at),
 CONSTRAINT fk_er_student FOREIGN KEY(student_id) REFERENCES students(student_id) ON DELETE CASCADE,
 CONSTRAINT fk_er_event FOREIGN KEY(event_id) REFERENCES events(event_id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS event_feedback (
 feedback_id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, student_id INT UNSIGNED NOT NULL, event_id INT UNSIGNED NOT NULL,
 rating TINYINT UNSIGNED NOT NULL, comments TEXT, submitted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY uq_feedback(student_id,event_id),
 CONSTRAINT fk_ef_student FOREIGN KEY(student_id) REFERENCES students(student_id) ON DELETE CASCADE,
 CONSTRAINT fk_ef_event FOREIGN KEY(event_id) REFERENCES events(event_id) ON DELETE CASCADE,
 CHECK(rating BETWEEN 1 AND 5)
) ENGINE=InnoDB;
